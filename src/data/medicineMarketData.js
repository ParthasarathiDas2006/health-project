/**
 * Helper to get a medicine by ID or by batch number
 */
export const findMedicineByIdOrBatch = (query) => {
  if (!query) return null;
  const qLower = query.toLowerCase().trim();
  return MEDICINE_MARKET_DATABASE.find((m) =>
    m.id.toLowerCase() === qLower ||
    m.batchNo.toLowerCase().includes(qLower) ||
    m.name.toLowerCase().includes(qLower) ||
    m.generic.toLowerCase().includes(qLower)
  ) || null;
};
